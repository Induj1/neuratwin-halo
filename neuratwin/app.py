def asset_config(asset_id):
    if asset_id not in ASSETS:
        raise HTTPException(404, 'Unknown asset.')
    with storage.database() as db:
        custom = db.execute('SELECT content FROM configurations WHERE asset_id=?', (asset_id,)).fetchone()
    if custom:
        return Asset.model_validate_json(custom['content'])
    asset = ASSETS[asset_id]
    calibration_path = ROOT/'data/demo_calibration.json'
    if calibration_path.exists():
        calibration = json.loads(calibration_path.read_text())
        return asset.model_copy(update={**calibration['parameters'], 'provenance': calibration['origin'] + ' Winding parameters and limits are demo assumptions.'})
    return asset


def get_readings(asset_id, scenario_name, dataset_id):
    if dataset_id:
        with storage.database() as db:
            row = db.execute('SELECT * FROM datasets WHERE id=? AND asset_id=?', (dataset_id, asset_id)).fetchone()
        if row is None:
            raise HTTPException(404, 'Imported dataset not found for this asset.')
        return [Reading.model_validate(r) for r in json.loads(row['readings'])], {'mode': 'Imported telemetry', 'name': row['name'], 'dataset_id': dataset_id,
                'note': 'User-supplied measurements. Asset parameters require verification; no ground-truth health labels assumed.'}
    if scenario_name not in SCENARIOS:
        raise HTTPException(404, 'Unknown scenario.')
    rows, _ = scenario(scenario_name, int(asset_id.split('-')[1]))
    return list(rows), {'mode': 'Synthetic replay', 'name': SCENARIOS[scenario_name]['name'], 'dataset_id': None,
                        'note': 'Generated by an independent three-node thermal plant. No physical transformer is connected.'}


def packet(asset_id, scenario_name, cursor, reduction, delay, dataset_id=None):
    asset = asset_config(asset_id)
    rows, provenance = get_readings(asset_id, scenario_name, dataset_id)
    cursor = min(max(cursor, 1), len(rows)-1)
    result = analyse(asset, rows[:cursor+1], reduction, delay)
    result.update(provenance=provenance, cursor=cursor, total_readings=len(rows), scenario=scenario_name)
    return result


